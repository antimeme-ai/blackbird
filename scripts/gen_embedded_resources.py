#!/usr/bin/env python3
"""Generate C++23 embedded resource definitions for a hermetic blackbird binary."""
import argparse
from pathlib import Path
import struct


def sanitize_ident(name: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in name)


def format_u8_array(symbol: str, data: bytes) -> list[str]:
    lines = [f"alignas(1) constexpr unsigned char {symbol}[{len(data)}] = {{"]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        row = ", ".join(f"0x{b:02x}U" for b in chunk)
        lines.append(f"    {row},")
    lines.append("};")
    return lines


def format_u64_array(symbol: str, data: bytes) -> list[str]:
    padded_len = ((len(data) + 7) // 8) * 8
    padded = data + b"\x00" * (padded_len - len(data))
    word_count = padded_len // 8
    lines = [
        f"constexpr std::size_t {symbol}_size = {len(data)}U;",
        f"constexpr std::uint64_t {symbol}_words[{word_count}] = {{",
    ]
    row_items: list[str] = []
    for offset in range(0, padded_len, 8):
        (word,) = struct.unpack_from("<Q", padded, offset)
        row_items.append(f"0x{word:016x}ULL")
        if len(row_items) == 4:
            lines.append("    " + ", ".join(row_items) + ",")
            row_items.clear()
    if row_items:
        lines.append("    " + ", ".join(row_items) + ",")
    lines.append("};")
    return lines


def generate(source_dir: Path, output_path: Path) -> None:
    profiles_dir = source_dir / "profiles" / "providers"
    profile_files = sorted(p for p in profiles_dir.glob("*.lua") if p.is_file())
    if not profile_files:
        raise RuntimeError(f"no provider profiles found in {profiles_dir}")

    integrations_dir = source_dir / "programs" / "integrations"
    saas_files = sorted(p for p in integrations_dir.glob("*.lua") if p.is_file())
    if not saas_files:
        raise RuntimeError(f"no SaaS packs found in {integrations_dir}")

    turn_path = source_dir / "programs" / "turn.lua"
    results_path = source_dir / "programs" / "instruments" / "results.lua"
    sr71_path = source_dir / "assets" / "sr71.png"
    for required in (turn_path, results_path, sr71_path):
        if not required.is_file():
            raise RuntimeError(f"missing required embedded resource: {required}")

    lines: list[str] = [
        "// Auto-generated by scripts/gen_embedded_resources.py. Do not edit.",
        '#include "blackbird/embedded_resources.hpp"',
        "#include <array>",
        "#include <bit>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <optional>",
        "#include <span>",
        "#include <string_view>",
        "",
        "static_assert(std::endian::native == std::endian::little,",
        '              "embedded binary word layout requires little-endian host");',
        "",
        "namespace blackbird {",
        "namespace {",
        "",
    ]

    profile_entries: list[tuple[str, str, int]] = []
    for path in profile_files:
        data = path.read_bytes()
        sym = "kProfile_" + sanitize_ident(path.stem)
        lines.extend(format_u8_array(sym, data))
        lines.append("")
        profile_entries.append((path.name, sym, len(data)))

    turn_data = turn_path.read_bytes()
    lines.extend(format_u8_array("kTurnWorkflow", turn_data))
    lines.append("")

    results_data = results_path.read_bytes()
    lines.extend(format_u8_array("kResultsInstrument", results_data))
    lines.append("")

    saas_entries: list[tuple[str, str, int]] = []
    for path in saas_files:
        data = path.read_bytes()
        sym = "kSaasPack_" + sanitize_ident(path.stem)
        lines.extend(format_u8_array(sym, data))
        lines.append("")
        saas_entries.append((path.stem, sym, len(data)))

    sr71_data = sr71_path.read_bytes()
    lines.extend(format_u64_array("kSr71Png", sr71_data))
    lines.append("")

    lines.append(
        "std::string_view as_text(const unsigned char *bytes, std::size_t size) noexcept {"
    )
    lines.append("  return {reinterpret_cast<const char *>(bytes), size};")
    lines.append("}")
    lines.append("")

    lines.append(
        f"const std::array<EmbeddedTextResource, {len(profile_entries)}> kProfiles = {{{{"
    )
    for filename, sym, size in profile_entries:
        lines.append(f'    {{"{filename}", as_text({sym}, {size}U)}},')
    lines.append("}};")
    lines.append("")

    lines.append(
        f"const std::array<EmbeddedTextResource, {len(saas_entries)}> kSaasPacks = {{{{"
    )
    for service, sym, size in saas_entries:
        lines.append(f'    {{"{service}", as_text({sym}, {size}U)}},')
    lines.append("}};")
    lines.append("")

    lines.append("} // namespace")
    lines.append("")
    lines.append(
        "std::span<const EmbeddedTextResource> embedded_provider_profiles() noexcept {"
    )
    lines.append("  return kProfiles;")
    lines.append("}")
    lines.append("")
    lines.append("std::string_view embedded_turn_workflow() noexcept {")
    lines.append(f"  return as_text(kTurnWorkflow, {len(turn_data)}U);")
    lines.append("}")
    lines.append("")
    lines.append("std::string_view embedded_results_instrument() noexcept {")
    lines.append(f"  return as_text(kResultsInstrument, {len(results_data)}U);")
    lines.append("}")
    lines.append("")
    lines.append("std::span<const EmbeddedTextResource> embedded_saas_packs() noexcept {")
    lines.append("  return kSaasPacks;")
    lines.append("}")
    lines.append("")
    lines.append("std::optional<std::string_view>")
    lines.append("find_embedded_saas_pack(std::string_view service) noexcept {")
    lines.append("  for (const auto &entry : kSaasPacks) {")
    lines.append("    if (entry.name == service)")
    lines.append("      return entry.content;")
    lines.append("  }")
    lines.append("  return std::nullopt;")
    lines.append("}")
    lines.append("")
    lines.append("std::span<const std::byte> embedded_sr71_png() noexcept {")
    lines.append(
        "  return {reinterpret_cast<const std::byte *>(kSr71Png_words), kSr71Png_size};"
    )
    lines.append("}")
    lines.append("")
    lines.append("} // namespace blackbird")
    lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    rendered = "\n".join(lines)
    if output_path.is_file() and output_path.read_text(encoding="utf-8") == rendered:
        return
    output_path.write_text(rendered, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generate(args.source_dir.resolve(), args.output.resolve())


if __name__ == "__main__":
    main()
